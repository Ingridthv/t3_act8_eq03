-- =====================================================================
-- Control Alumnos - V1: esquema inicial (PostgreSQL)
-- Roles: administrador, docente, estudiante
-- Relación N:M: inscripciones <-> grupos (tabla intermedia cargas_academicas)
-- Compatible con PostgreSQL 14 o superior
-- =====================================================================

-- Calificación válida: 0.0 a 10.0
CREATE DOMAIN calificacion AS numeric(3,1)
  CHECK (VALUE >= 0 AND VALUE <= 10);

-- ---------------------------------------------------------------------
-- Roles
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  text NOT NULL UNIQUE
          CHECK (nombre IN ('administrador','docente','estudiante'))
);

-- ---------------------------------------------------------------------
-- Docentes
-- ---------------------------------------------------------------------
CREATE TABLE docentes (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  clave      varchar(10) NOT NULL UNIQUE,            -- DOC-001
  nombre     text NOT NULL,
  apellidos  text NOT NULL,
  correo     text NOT NULL UNIQUE,
  telefono   varchar(15),                            -- para SMS / WhatsApp
  estatus    text NOT NULL DEFAULT 'activo'
             CHECK (estatus IN ('activo','licencia','baja')),
  creado_en  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Carreras
-- ---------------------------------------------------------------------
CREATE TABLE carreras (
  id                  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave               varchar(10) NOT NULL UNIQUE,   -- SIS, IND, PSI...
  nombre              text NOT NULL UNIQUE,
  duracion_semestres  smallint NOT NULL DEFAULT 9
                      CHECK (duracion_semestres BETWEEN 1 AND 14),
  coordinador_id      uuid REFERENCES docentes(id) ON DELETE SET NULL,
  activa              boolean NOT NULL DEFAULT true
);

-- ---------------------------------------------------------------------
-- Alumnos
-- ---------------------------------------------------------------------
CREATE TABLE alumnos (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  matricula         varchar(12) NOT NULL UNIQUE,
  nombre            text NOT NULL,
  apellido_paterno  text NOT NULL,
  apellido_materno  text,
  correo            text NOT NULL UNIQUE,
  telefono          varchar(15),                     -- para SMS / WhatsApp
  carrera_id        smallint NOT NULL REFERENCES carreras(id),
  semestre_actual   smallint NOT NULL CHECK (semestre_actual BETWEEN 1 AND 14),
  anio_ingreso      smallint NOT NULL CHECK (anio_ingreso BETWEEN 2000 AND 2100),
  estatus           text NOT NULL DEFAULT 'activo'
                    CHECK (estatus IN ('activo','baja','egresado')),
  codigo_postal     char(5),                         -- se valida con Zippopotam.us
  estado            text,
  foto_url          text,
  creado_en         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX alumnos_carrera_idx ON alumnos (carrera_id);
CREATE INDEX alumnos_anio_idx    ON alumnos (anio_ingreso);
CREATE INDEX alumnos_estatus_idx ON alumnos (estatus);

-- ---------------------------------------------------------------------
-- Usuarios del sistema (login por correo)
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  correo                text NOT NULL,
  password_hash         text NOT NULL,               -- BCrypt, nunca en claro
  rol_id                smallint NOT NULL REFERENCES roles(id),
  alumno_id             uuid UNIQUE REFERENCES alumnos(id)  ON DELETE CASCADE,
  docente_id            uuid UNIQUE REFERENCES docentes(id) ON DELETE CASCADE,
  activo                boolean NOT NULL DEFAULT true,
  debe_cambiar_password boolean NOT NULL DEFAULT true,  -- true con contraseña temporal
  ultimo_acceso         timestamptz,
  creado_en             timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT (alumno_id IS NOT NULL AND docente_id IS NOT NULL))
);
CREATE UNIQUE INDEX usuarios_correo_uk ON usuarios (lower(correo));

-- Logout / invalidación de JWT: se guarda el identificador (jti) del token
CREATE TABLE tokens_invalidados (
  jti            varchar(64) PRIMARY KEY,
  usuario_id     uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expira_en      timestamptz NOT NULL,
  invalidado_en  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX tokens_invalidados_exp_idx ON tokens_invalidados (expira_en);

-- Recuperación de contraseña: se guarda el hash del token enviado por correo
CREATE TABLE tokens_recuperacion (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  usuario_id  uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  token_hash  text NOT NULL UNIQUE,
  expira_en   timestamptz NOT NULL,
  usado       boolean NOT NULL DEFAULT false,
  creado_en   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX tokens_recuperacion_usuario_idx ON tokens_recuperacion (usuario_id);

-- ---------------------------------------------------------------------
-- Periodos escolares
-- ---------------------------------------------------------------------
CREATE TABLE periodos (
  id            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio          smallint NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
  tipo          text NOT NULL CHECK (tipo IN ('ENE-JUL','AGO-DIC')),
  fecha_inicio  date NOT NULL,
  fecha_fin     date NOT NULL,
  es_actual     boolean NOT NULL DEFAULT false,
  -- "Enero-Julio 2020" / "Agosto-Diciembre 2020"
  nombre        text GENERATED ALWAYS AS (
                  CASE tipo WHEN 'ENE-JUL' THEN 'Enero-Julio ' ELSE 'Agosto-Diciembre ' END
                  || anio::text
                ) STORED,
  UNIQUE (anio, tipo),
  CHECK (fecha_fin > fecha_inicio)
);
-- Solo puede haber un periodo actual
CREATE UNIQUE INDEX periodos_un_actual_idx ON periodos (es_actual) WHERE es_actual;

-- ---------------------------------------------------------------------
-- Materias (catálogo) y grupos (oferta de una materia en un periodo)
-- ---------------------------------------------------------------------
CREATE TABLE materias (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  clave       varchar(10) NOT NULL UNIQUE,           -- SIS-101
  nombre      text NOT NULL,
  creditos    smallint NOT NULL CHECK (creditos BETWEEN 1 AND 20),
  semestre    smallint NOT NULL CHECK (semestre BETWEEN 1 AND 14),
  carrera_id  smallint NOT NULL REFERENCES carreras(id),
  activa      boolean NOT NULL DEFAULT true
);
CREATE INDEX materias_carrera_idx ON materias (carrera_id);

CREATE TABLE grupos (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  materia_id    uuid NOT NULL REFERENCES materias(id),
  periodo_id    smallint NOT NULL REFERENCES periodos(id),
  docente_id    uuid NOT NULL REFERENCES docentes(id),
  nombre_grupo  char(1) NOT NULL,                    -- A, B, C...
  horario       text,
  cupo          smallint CHECK (cupo > 0),
  UNIQUE (materia_id, periodo_id, nombre_grupo)
);
CREATE INDEX grupos_periodo_idx ON grupos (periodo_id);
CREATE INDEX grupos_docente_idx ON grupos (docente_id);

-- ---------------------------------------------------------------------
-- Inscripciones y su carga de materias (relación N:M con grupos)
-- ---------------------------------------------------------------------
CREATE TABLE inscripciones (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  alumno_id          uuid NOT NULL REFERENCES alumnos(id),
  periodo_id         smallint NOT NULL REFERENCES periodos(id),
  fecha_inscripcion  date NOT NULL DEFAULT current_date,
  estatus            text NOT NULL DEFAULT 'inscrito'
                     CHECK (estatus IN ('inscrito','baja')),
  UNIQUE (alumno_id, periodo_id)
);
CREATE INDEX inscripciones_periodo_idx ON inscripciones (periodo_id);

CREATE TABLE cargas_academicas (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  inscripcion_id  uuid NOT NULL REFERENCES inscripciones(id) ON DELETE CASCADE,
  grupo_id        uuid NOT NULL REFERENCES grupos(id),
  UNIQUE (inscripcion_id, grupo_id)
);
CREATE INDEX cargas_grupo_idx ON cargas_academicas (grupo_id);

-- ---------------------------------------------------------------------
-- Calificaciones (una por materia cursada)
-- ---------------------------------------------------------------------
CREATE TABLE calificaciones (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  carga_id      uuid NOT NULL UNIQUE REFERENCES cargas_academicas(id) ON DELETE CASCADE,
  parcial       calificacion,
  final         calificacion,
  -- Aprobatoria mínima: 6.0 (cambiar aquí si la escuela usa otra)
  estatus       text GENERATED ALWAYS AS (
                  CASE WHEN final IS NULL THEN 'pendiente'
                       WHEN final >= 6.0  THEN 'aprobado'
                       ELSE 'reprobado' END
                ) STORED,
  capturada_en  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Vistas para Inicio y Reportes
-- ---------------------------------------------------------------------
-- "Solo alumnos inscritos actualmente"
CREATE VIEW vw_alumnos_inscritos_actuales AS
SELECT a.*
FROM alumnos a
JOIN inscripciones i ON i.alumno_id = a.id AND i.estatus = 'inscrito'
JOIN periodos p      ON p.id = i.periodo_id AND p.es_actual;

-- Promedio general de cada alumno (se calcula, no se guarda)
CREATE VIEW vw_promedio_alumno AS
SELECT a.id AS alumno_id, a.matricula,
       round(avg(c.final), 1) AS promedio
FROM alumnos a
JOIN inscripciones i      ON i.alumno_id = a.id
JOIN cargas_academicas ca ON ca.inscripcion_id = i.id
JOIN calificaciones c     ON c.carga_id = ca.id
GROUP BY a.id, a.matricula;
